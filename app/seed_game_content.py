def add_question(stage: Stage, position: int, data: dict, question_type: QuestionType) -> Question:
    return Question(
        stage_id=stage.id,
        position=position,
        title=data["title"],
        text=data["text"],
        correct_answer=data["answer"],
        explanation=data["explanation"],
        title_kk=data["title_kk"],
        text_kk=data["text_kk"],
        correct_answer_kk=data["answer_kk"],
        explanation_kk=data["explanation_kk"],
        duration_seconds=data.get("duration", 60),
        submission_seconds=20,
        personal_answers_enabled=False,
        team_answers_enabled=True,
        personal_points=0,
        team_points=5,
        question_type=question_type,
        options_json=json.dumps(data.get("options", []), ensure_ascii=False),
        show_anonymous_answers=True,
    )


def seed_game_content() -> None:
    Base.metadata.create_all(engine)
    with SessionLocal() as db:
        event = db.scalar(select(Event).where(Event.active.is_(True)).order_by(Event.id)) or db.scalar(
            select(Event).order_by(Event.id)
        )
        if not event:
            raise RuntimeError("Сначала создайте мероприятие в админке.")
        existing = db.scalar(select(GameProgram).where(
            GameProgram.event_id == event.id,
            GameProgram.title == PROGRAM_TITLE,
        ))
        if existing:
            print(f"Игра уже существует: id={existing.id}. Повторное создание пропущено.")
            return

        start_position = (db.scalar(select(func.max(Stage.position)).where(Stage.event_id == event.id)) or 0) + 1
        chgk = Stage(
            event_id=event.id,
            position=start_position,
            stage_type=StageType.QUIZ,
            title="1 этап · Что? Где? Когда?",
            title_kk="1 кезең · Не? Қайда? Қашан?",
            description="Пять командных вопросов со свободным ответом. Проверка ответов — вручную.",
            description_kk="Еркін жауап берілетін бес командалық сұрақ. Жауаптар қолмен тексеріледі.",
            default_duration_seconds=60,
            default_submission_seconds=20,
            default_team_points=5,
        )
        choice = Stage(
            event_id=event.id,
            position=start_position + 1,
            stage_type=StageType.QUIZ,
            title="2 этап · Выбор решения",
            title_kk="2 кезең · Шешімді таңдау",
            description="Пять задач с несколькими вариантами ответа.",
            description_kk="Бірнеше жауап нұсқасы бар бес тапсырма.",
            default_duration_seconds=60,
            default_submission_seconds=20,
            default_team_points=5,
        )
        detective = Stage(
            event_id=event.id,
            position=start_position + 2,
            stage_type=StageType.DETECTIVE,
            title="3 этап · Детективная гонка",
            title_kk="3 кезең · Детективтік жарыс",
            description="Для каждой команды создаётся отдельный логический кейс. Каждый участник получает персональную улику.",
            description_kk="Әр командаға жеке логикалық іс жасалады. Әр қатысушы жеке айғақ алады.",
            detective_duration_seconds=1200,
            detective_points="30,25,20,17,14,10",
        )
        db.add_all([chgk, choice, detective])
        db.flush()

        db.add_all([
            add_question(chgk, index, data, QuestionType.TEXT)
            for index, data in enumerate(CHGK_QUESTIONS, 1)
        ])
        db.add_all([
            add_question(choice, index, data, data["type"])
            for index, data in enumerate(CHOICE_QUESTIONS, 1)
        ])

        program = GameProgram(
            event_id=event.id,
            title=PROGRAM_TITLE,
            description="ЧГК → выбор решения → детективная гонка",
        )
        db.add(program)
        db.flush()
        for position, stage in enumerate((chgk, choice, detective), 1):
            db.add(GameProgramStage(program_id=program.id, stage_id=stage.id, position=position))
        db.commit()
        print(
            f"Создана игра id={program.id}: 3 этапа, "
            f"{len(CHGK_QUESTIONS) + len(CHOICE_QUESTIONS)} вопросов."
        )


if __name__ == "__main__":
    seed_game_content()
