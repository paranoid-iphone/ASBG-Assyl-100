def repair() -> None:
    with SessionLocal() as db:
        stages = db.scalars(select(Stage).order_by(Stage.id)).all()
        stage = next((item for item in stages if len(item.questions) == 5 and "?" in item.title), None)
        if not stage:
            return
        stage.title, stage.title_kk, stage.description, stage.description_kk = STAGE
        for question, data in zip(stage.questions, QUESTIONS, strict=True):
            (
                question.title,
                question.text,
                question.correct_answer,
                question.explanation,
                question.title_kk,
                question.text_kk,
                question.correct_answer_kk,
                question.explanation_kk,
            ) = data
        db.commit()


if __name__ == "__main__":
    repair()
